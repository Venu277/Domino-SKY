import { buildSubstitutionMap, substitutePlaceholders } from './placeholders.js';
import type { RawAdvisorOutput } from './schema.js';
import type { AdvisorRecommendation, PlannerCandidate, SimulationMetrics } from '../types.js';

export interface VerifierInput {
  rawOutput: RawAdvisorOutput;
  candidates: PlannerCandidate[];
  baselineMetrics: SimulationMetrics;
  knownEntityIds?: string[]; // flight IDs, tail IDs, crew IDs, airport codes
}

export interface VerificationResult {
  isValid: boolean;
  error?: string;
  verified?: AdvisorRecommendation;
}

/**
 * Strict Verifier that enforces:
 * 1. AI only selected an existing candidate ID generated by the planner.
 * 2. AI wrote text using {{placeholders}} rather than fabricating raw digits.
 * 3. All placeholders resolve to deterministic engine metrics.
 * 4. Any raw digits in the text match strictly whitelisted entity numbers or ordinals.
 */
export function verifyAdvisorOutput(
  input: VerifierInput,
  path: 'llm' | 'retry' | 'fallback' = 'llm'
): VerificationResult {
  const { rawOutput, candidates, baselineMetrics, knownEntityIds = [] } = input;

  // 1. Validate Candidate ID
  const validCandidateIds = new Set(candidates.map((c) => c.id));
  if (!validCandidateIds.has(rawOutput.recommendedCandidateId)) {
    return {
      isValid: false,
      error: `Invalid candidate ID '${rawOutput.recommendedCandidateId}'. Must be one of: ${Array.from(validCandidateIds).join(', ')}`,
    };
  }

  // Build whitelist of numbers allowed to appear as raw digits in AI prose
  // (e.g., candidate numbers "1", "2" from C1/C2, ordinals, flight numbers if stripped)
  const whitelist = new Set<string>();

  // Add numbers appearing in entity IDs (like DS0201 -> 0201, 201)
  for (const id of knownEntityIds) {
    const numMatches = id.match(/\d+/g);
    if (numMatches) {
      for (const n of numMatches) {
        whitelist.add(n);
        whitelist.add(parseInt(n, 10).toString());
      }
    }
  }

  // Add candidate indices (1, 2, 3...)
  for (const c of candidates) {
    const num = c.id.replace(/\D/g, '');
    if (num) whitelist.add(num);
  }

  // Allowed small ordinal/structural numbers
  whitelist.add('1');
  whitelist.add('2');
  whitelist.add('3');
  whitelist.add('4');
  whitelist.add('5');

  // Check for un-whitelisted raw digits in raw LLM text
  const checkTextForRawDigits = (text: string, fieldName: string): string | null => {
    // Strip out all {{placeholder}} tokens first before checking remaining text
    const textWithoutPlaceholders = text.replace(/\{\{[^}]+\}\}/g, ' ');

    // Match any standalone digits or numbers
    const matches = textWithoutPlaceholders.match(/\b\d+(\.\d+)?\b/g);
    if (matches) {
      for (const token of matches) {
        // Strip leading zeros for check
        const cleanToken = token.includes('.') ? token : parseInt(token, 10).toString();
        if (!whitelist.has(token) && !whitelist.has(cleanToken)) {
          return `Forbidden raw digit '${token}' found in ${fieldName}. You must use {{placeholders}} like {{${rawOutput.recommendedCandidateId}.stranded}} instead of raw numbers.`;
        }
      }
    }
    return null;
  };

  // Check rationale
  const rationaleErr = checkTextForRawDigits(rawOutput.rationale, 'rationale');
  if (rationaleErr) return { isValid: false, error: rationaleErr };

  // Check tradeoffs
  for (let i = 0; i < rawOutput.tradeoffs.length; i++) {
    const err = checkTextForRawDigits(rawOutput.tradeoffs[i], `tradeoffs[${i}]`);
    if (err) return { isValid: false, error: err };
  }

  // Check alternatives
  for (let i = 0; i < rawOutput.alternativesConsidered.length; i++) {
    const err = checkTextForRawDigits(
      rawOutput.alternativesConsidered[i],
      `alternativesConsidered[${i}]`
    );
    if (err) return { isValid: false, error: err };
  }

  // 2. Perform Placeholder Substitution
  const { map: subMap } = buildSubstitutionMap({ baselineMetrics, candidates });

  const subRationale = substitutePlaceholders(rawOutput.rationale, subMap);
  const subTradeoffs = rawOutput.tradeoffs.map((t) => substitutePlaceholders(t, subMap).resultText);
  const subAlternatives = rawOutput.alternativesConsidered.map(
    (a) => substitutePlaceholders(a, subMap).resultText
  );

  // Check for any un-substituted {{...}} placeholders
  const unres1 = subRationale.resultText.match(/\{\{([^}]+)\}\}/);
  if (unres1) {
    return {
      isValid: false,
      error: `Unresolved placeholder {{${unres1[1]}}} in rationale. Check candidate/metric naming.`,
    };
  }

  return {
    isValid: true,
    verified: {
      recommendedCandidateId: rawOutput.recommendedCandidateId,
      rationale: subRationale.resultText,
      tradeoffs: subTradeoffs,
      alternativesConsidered: subAlternatives,
      path,
    },
  };
}

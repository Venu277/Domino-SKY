import type { RawAdvisorOutput } from '@domino/main';

export interface LLMPromptContext {
  closedAirport: string;
  closureWindow: string;
  durationMinutes: number;
  baselineMetrics: {
    strandedPaxTotal: number;
    totalDelayMinutes: number;
    delayedFlightsCount: number;
    cancelledFlightsCount: number;
    crewsAtRiskCount: number;
    onTimePct: number;
  };
  candidates: Array<{
    id: string;
    title: string;
    summary: string;
    score: number;
    netStrandedSaved: number;
    netDelaySaved: number;
    actions: unknown[];
  }>;
}

export interface LLMProvider {
  name: string;
  generateRecommendation(
    context: LLMPromptContext,
    retryErrorNotice?: string
  ): Promise<RawAdvisorOutput>;
}

/**
 * Builds the strict system and user prompt enforcing zero-hallucination placeholders.
 */
export function buildPrompt(
  context: LLMPromptContext,
  retryErrorNotice?: string
): { systemInstruction: string; userPrompt: string } {
  const candidateIds = context.candidates.map((c) => c.id).join(', ');

  const systemInstruction = `You are the Senior Network Operations Dispatcher for airline Domino Sky.
Your job is to review operational recovery candidates generated by the deterministic engine and recommend the best candidate.

CRITICAL NON-NEGOTIABLE RULES:
1. You may ONLY choose a candidate ID from this list: [${candidateIds}]. Never invent candidate IDs.
2. NEVER write any raw numbers or metrics yourself (e.g. do not write "125 passengers" or "recovers 340 minutes").
3. You MUST write all numerical metrics using placeholders enclosed in double braces:
   - For candidate metrics: {{C1.id}}, {{C1.title}}, {{C1.stranded}}, {{C1.delay}}, {{C1.cancellations}}, {{C1.delayedCount}}, {{C1.crewsAtRisk}}, {{C1.onTimePct}}, {{C1.strandedSaved}}, {{C1.delaySaved}}, {{C1.score}}
   - For baseline metrics: {{baseline.stranded}}, {{baseline.delay}}, {{baseline.cancellations}}, {{baseline.delayedCount}}, {{baseline.crewsAtRisk}}, {{baseline.onTimePct}}
4. A deterministic verifier strictly inspects your text. If ANY un-whitelisted standalone raw digits appear in your rationale, tradeoffs, or alternatives, your response will be rejected!
5. You MUST return ONLY valid JSON matching this schema:
{
  "recommendedCandidateId": "C1",
  "rationale": "Clear operational reasoning using {{placeholders}}",
  "tradeoffs": ["Trade-off 1", "Trade-off 2"],
  "alternativesConsidered": ["Evaluation of alternative candidate using {{placeholders}}"]
}`;

  let userPrompt = `DISRUPTED SCENARIO:
- Hub Closed: ${context.closedAirport}
- Closure Window: ${context.closureWindow} (${context.durationMinutes} min ground stop)
- Baseline Network Impact: {{baseline.stranded}} stranded passengers, {{baseline.delay}} total delay minutes across {{baseline.delayedCount}} flights, {{baseline.cancellations}} cancellations, and {{baseline.crewsAtRisk}} crews risking duty timeout.

PLANNER-GENERATED CANDIDATES:
${context.candidates
  .map(
    (c) =>
      `• Candidate {{${c.id}.id}}: "${c.title}"
  Summary: ${c.summary}
  Metrics: saves {{${c.id}.strandedSaved}} pax, recovers {{${c.id}.delaySaved}} delay mins, {{${c.id}.onTimePct}}% on-time, score: {{${c.id}.score}}`
  )
  .join('\n\n')}

Recommend the optimal candidate. Explain the trade-offs and compare alternatives using {{placeholders}}.`;

  if (retryErrorNotice) {
    userPrompt += `\n\n[WARNING - PREVIOUS RESPONSE REJECTED BY VERIFIER]:
${retryErrorNotice}
Please fix the above error immediately. Remember: NO RAW DIGITS. Use {{placeholders}} for all numbers.`;
  }

  return { systemInstruction, userPrompt };
}

/**
 * Gemini Provider implementation using standard REST API (works seamlessly across all Node versions).
 */
export class GeminiProvider implements LLMProvider {
  name = 'gemini';
  private apiKey: string;
  private model: string;

  constructor(apiKey: string, model = 'gemini-2.5-flash') {
    this.apiKey = apiKey;
    this.model = model;
  }

  async generateRecommendation(
    context: LLMPromptContext,
    retryErrorNotice?: string
  ): Promise<RawAdvisorOutput> {
    const { systemInstruction, userPrompt } = buildPrompt(context, retryErrorNotice);

    const url = `https://generativelanguage.googleapis.com/v1beta/models/${this.model}:generateContent?key=${this.apiKey}`;

    const payload = {
      systemInstruction: {
        parts: [{ text: systemInstruction }],
      },
      contents: [
        {
          role: 'user',
          parts: [{ text: userPrompt }],
        },
      ],
      generationConfig: {
        responseMimeType: 'application/json',
        temperature: 0.2,
      },
    };

    const response = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload),
    });

    if (!response.ok) {
      const errText = await response.text();
      throw new Error(`Gemini API call failed (${response.status}): ${errText}`);
    }

    const data = await response.json();
    const candidate = data.candidates?.[0];
    const textContent = candidate?.content?.parts?.[0]?.text;

    if (!textContent) {
      throw new Error('Gemini returned an empty response.');
    }

    const parsed = JSON.parse(textContent);
    return parsed as RawAdvisorOutput;
  }
}
